/**
 * The templates to offer a company: the ones made for its industry first
 * (in library order), then the general ones. Never empty — an unknown or
 * missing industry still gets the general set.
 */
export function libraryFor(industryId: string | null | undefined): LibraryTemplate[] {
  const general = LIBRARY.filter((t) => t.industries.length === 0);
  const id = industryId?.trim();
  if (!id) return general;
  return [...LIBRARY.filter((t) => t.industries.includes(id)), ...general];
}
