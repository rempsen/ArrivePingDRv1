/**
 * Job forms v2 — the starter template library.
 *
 * The ready-made job templates a new company can add in one click from the
 * template builder. Each one is a complete schema-2 form (see form-model.ts):
 * sections, safety reminders, inspections that flag on Fail, follow-up
 * questions that only appear when needed, office-only notes, and a sign-off.
 *
 * Rules every entry keeps (the library test enforces them):
 * - `normalizeForm(form)` returns the form unchanged — no bad types, no
 *   duplicate options, every "show only if" points at an earlier question.
 * - `showIf` / `flagOn` values are real answers: "yes"/"no", "pass"/"fail"/"na",
 *   or an exact option string.
 * - Item ids are short slugs, unique within the template and stable: answers
 *   are stored by id, so never rename one in a shipped template.
 * - `industries` holds IndustryPreset ids (services/industry-presets.ts);
 *   an empty list means the template suits every business.
 *
 * Treat these objects as read-only: copy (`structuredClone`) before editing.
 */

import { FORM_SCHEMA, type FormDef, type FormItem } from "./form-model";

export interface LibraryTemplate {
  /** Stable slug, e.g. "hvac-furnace-tune-up". */
  key: string;
  name: string;
  /** IndustryPreset ids it fits; [] = general (fits everyone). */
  industries: string[];
  category: string;
  /** One plain sentence for the library card. */
  description: string;
  estimatedMins: number;
  /** Hex colour for the card and the template. */
  color: string;
  /** A lucide-react icon name in kebab-case. */
  icon: string;
  form: FormDef;
}

const form = (items: FormItem[]): FormDef => ({ schema: FORM_SCHEMA, items });

